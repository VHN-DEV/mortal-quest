export const getRealmById = (id, type = 'tuvi', race = 'HUMAN') => {
    let list = HUMAN_REALMS;
    if (type === 'body') list = BODY_REALMS;
    else if (type === 'soul') list = SOUL_REALMS;
    else if (type === 'sword') list = SWORD_PATH_REALMS;
    else if (type === 'soul_path') list = SOUL_PATH_REALMS;
    else {
        list = RACE_DATA[race]?.realms || HUMAN_REALMS;
    }
    const found = list.find(r => r.id === id);
    if (found) return found;

    // Safety fallback: if requested ID exceeds the highest realm, return the peak realm instead of index 0
    const maxRealm = list[list.length - 1];
    if (maxRealm && id > maxRealm.id) {
        return maxRealm;
    }

    return list[0];
};
