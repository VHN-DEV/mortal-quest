function _classifyItemRaw(item) {
    if (!item) {
        return { category: 'ky_vat_di_bao', subcategory: 'ngoc_gian' };
    }

    const name = item.name || '';
    const type = item.type || '';
    const quality = item.quality || '';
    const id = item.id || '';
    const effect = item.effect || {};

    // 1. Direct explicit overrides from the database item definition!
    // Check if 'categories' (plural array) is defined:
    if (item.categories && Array.isArray(item.categories) && item.categories.length > 0) {
        const parsed = item.categories.map(c => {
            if (typeof c === 'string') {
                return { category: c, subcategory: 'default', subSubcategory: 'default' };
            }
            return {
                category: c.category || 'default',
                subcategory: c.subcategory || 'default',
                subSubcategory: c.subSubcategory || 'default'
            };
        });
        return {
            category: parsed[0].category,
            subcategory: parsed[0].subcategory,
            subSubcategory: parsed[0].subSubcategory,
            allClassifications: parsed
        };
    }

    // Check if 'shopCategory' (single override) is defined:
    if (item.shopCategory) {
        const single = { 
            category: item.shopCategory, 
            subcategory: item.shopSubcategory || 'default', 
            subSubcategory: item.shopSubSubcategory || 'default' 
        };
        return {
            ...single,
            allClassifications: [single]
        };
    }

    // 1. Dịch Vụ
    if (type === 'service' || id === 'ngo_dao_that') {
        return { category: 'dich_vu', subcategory: 'thue_phong' };
    }

    // 1b. Danh sách kỳ vật / Điển tịch ghi chép (Ngọc Giản)
    if (item.action && item.action.startsWith('open_')) {
        return { category: 'ky_vat_di_bao', subcategory: 'ngoc_gian' };
    }

    // 1c. Linh Thú Đại (Túi chứa Linh Thú)
    if (type === 'artifact') {
        return { category: 'ky_vat_di_bao', subcategory: 'default' };
    }

    // 2. Dị Hỏa
    if (type === 'di_hoa' || type === 'flame' || id.startsWith('di_hoa')) {
        return { category: 'ky_vat_di_bao', subcategory: 'di_hoa' };
    }

    // 3. Phù Lục tools (Bút, Mực, Giấy)
    if (type === 'talisman_pen' || type === 'talisman_ink' || type === 'talisman_paper') {
        return { category: 'phu_luc', subcategory: 'phu_cu' };
    }

    // 4. Luyện Khí (Bản Vẽ and Đài/Lò/Lư Luyện Khí)
    if (effect.type === 'learn_smithing_recipe' || id.startsWith('bv_') || type === 'smithing_recipe') {
        return { category: 'luyen_khi', subcategory: 'ban_ve' };
    }
    if (type === 'smithing_tool') {
        return { category: 'luyen_khi', subcategory: 'dai_luyen_khi' };
    }

    // 7. Trận Pháp
    if (type === 'formation' || effect.type === 'learn_formation' || id.startsWith('td_')) {
        let sub = 'tu_linh_tran';
        if (name.includes('Tụ Linh') || id.includes('tu_linh')) {
            sub = 'tu_linh_tran';
        } else if (name.includes('Ảo Ảnh') || name.includes('Huyễn') || id.includes('ao_anh')) {
            sub = 'huyen_tran';
        } else if (name.includes('Sát Kiếm') || name.includes('Công Kích') || id.includes('sat_kiem')) {
            sub = 'cong_kich_tran';
        } else if (name.includes('Hộ Tông') || name.includes('Phòng Ngự') || id.includes('ho_tong')) {
            sub = 'phong_ngu_tran';
        } else if (name.includes('Khốn')) {
            sub = 'khon_tran';
        } else if (name.includes('Truyền Tống')) {
            sub = 'truyen_tong_tran';
        } else if (name.includes('Cấm Chế')) {
            sub = 'cam_che';
        }
        return { category: 'tran_phap', subcategory: sub };
    }

    // 8. Khôi Lỗi
    if (type === 'puppet' || type === 'corpse' || effect.type === 'learn_puppet_recipe' || effect.type === 'learn_corpse_recipe' || id.startsWith('bp_')) {
        let sub = 'linh_khoi';
        if (type === 'corpse' || effect.type === 'learn_corpse_recipe' || id.includes('thi_')) {
            sub = 'thi_khoi';
        }
        return { category: 'khoi_loi', subcategory: sub };
    }

    // 5. Công Pháp
    const isBook = type === 'book' || type === 'technique' || type === 'recipe' || effect.type === 'learn_secret' || effect.type === 'learn_technique' || effect.type === 'learn_alchemy_recipe';
    const isManual = effect.type === 'unlock_profession';

    if (isBook || isManual) {
        let sub = 'tu_luyen';
        if (name.includes('Luyện Thể') || id.includes('luyen_the') || id.includes('kim_than')) {
            sub = 'luyen_the';
        } else if (name.includes('Thần Hồn') || name.includes('Luyện Hồn') || id.includes('duong_than')) {
            sub = 'than_hon';
        } else if (name.includes('Bí Thuật') || id.includes('bi_thuat') || type === 'recipe' || isManual) {
            sub = 'bi_thuat';
        } else if (name.includes('Thần Thông') || id.includes('than_thong')) {
            sub = 'than_thong';
        } else if (name.includes('Độn Thuật') || id.includes('don_thuat')) {
            sub = 'don_thuat';
        } else if (name.includes('Kiếm Quyết') || id.includes('kiem_quyet') || id.includes('kiem')) {
            sub = 'kiem_quyet';
        } else if (name.includes('Ma Công') || id.includes('ma_cong') || id.includes('ma_dien')) {
            sub = 'ma_cong';
        }
        return { category: 'cong_phap', subcategory: sub };
    }

    // 6. Phù Lục (standard talismans)
    if (type === 'talisman' || type === 'talisman_recipe' || id.startsWith('pv_')) {
        let sub = 'cong_kich';
        if (name.includes('Cầu Phù') || name.includes('Lôi Phù') || name.includes('Công Kích') || id.includes('hoa_cau') || id.includes('thien_loi')) {
            sub = 'cong_kich';
        } else if (name.includes('Kim Cương') || name.includes('Phòng Ngự') || id.includes('kim_cuong')) {
            sub = 'phong_ngu';
        } else if (name.includes('Thần Hành') || name.includes('Thuấn Di') || name.includes('Phá Không') || id.includes('than_hanh') || id.includes('thun_di') || id.includes('pha_khong')) {
            sub = 'don_thuat';
        } else if (name.includes('Trấn Áp')) {
            sub = 'tran_ap';
        } else if (name.includes('Triệu Hồi')) {
            sub = 'trieu_hoi';
        } else if (name.includes('Truyền Âm')) {
            sub = 'truyen_am';
        }
        return { category: 'phu_luc', subcategory: sub };
    }

    // 9. Linh Thú
    if (type === 'beast_egg' || type === 'beast_food') {
        let sub = 'linh_thu';
        const isEgg = type === 'beast_egg';
        const isKyTrung = id.includes('ky_trung') || id.includes('phe_kim') || id.includes('bang_tam') || id.includes('tri_chu') || id.includes('hac_xa') || id.includes('nga') || id.includes('uynh');

        if (isEgg) {
            sub = isKyTrung ? 'trung_ky_trung' : 'trung_linh_thu';
        } else {
            sub = isKyTrung ? 'ky_trung' : 'linh_thu';
        }
        return { category: 'linh_thu', subcategory: sub };
    }

    // 10. Đan Dược
    if (type === 'consumable') {
        let sub = 'khac';
        if (name.includes('Trúc Cơ') || name.includes('Kết Đan') || name.includes('Nguyên Anh') || name.includes('Hóa Thần') || name.includes('Đột Phá') || id.includes('breakthrough')) {
            sub = 'dot_pha';
        } else if (name.includes('Ngự Thú') || name.includes('Hồi Phục') || name.includes('Khí Huyết') || name.includes('Bổ Nguyên') || name.includes('Ngọc Lộ') || id.includes('bo_nguyen') || id.includes('restore')) {
            sub = 'hoi_phuc';
        } else if (name.includes('Hồi Huyết') || name.includes('Trị Thương')) {
            sub = 'tri_thuong';
        } else if (name.includes('Giải Độc') || id.includes('giai_doc')) {
            sub = 'giai_doc';
        } else if (name.includes('Luyện Thể') || id.includes('luyen_the')) {
            sub = 'luyen_the';
        } else if (name.includes('Tăng Thọ') || name.includes('Tiêu Dao Quả') || id.includes('tieu_dao_qua')) {
            sub = 'tang_tho';
        } else if (name.includes('Ngưng Khí') || name.includes('Ngộ Đạo') || name.includes('Song Tu') || id.includes('ngung_khi') || id.includes('ngo_dao') || id.includes('song_tu')) {
            sub = 'tu_luyen';
        }
        return { category: 'dan_duoc', subcategory: sub };
    }

    // 11. Pháp Bảo
    const isEquipment = ['weapon', 'armor', 'accessory', 'treasure', 'head', 'necklace', 'shoes', 'attackArtifact', 'defenseArtifact', 'flightArtifact', 'spaceArtifact', 'formationArtifact', 'supportArtifact', 'soulArtifact', 'cauldron', 'craftingArtifact'].includes(type);
    if (isEquipment) {
        let sub = 'phap_khi';
        if (name.includes('Phù Bảo') || id.includes('phu_bao')) {
            sub = 'phu_bao';
        } else if (quality === 'Pháp Khí') {
            sub = 'phap_khi';
        } else if (quality === 'Linh Khí') {
            sub = 'dinh_giai';
        } else if (quality === 'Pháp Bảo') {
            sub = 'phap_bao_sub';
        } else if (quality === 'Cổ Bảo') {
            sub = 'co_bao';
        } else if (quality === 'Linh Bảo') {
            sub = 'linh_bao';
        } else if (quality === 'Thông Thiên Linh Bảo') {
            sub = 'thong_thien';
        } else if (quality === 'Huyền Thiên Chi Bảo') {
            sub = 'huyen_thien';
        } else if (quality === 'Tiên Khí') {
            sub = 'tien_khi';
        } else {
            sub = 'phap_khi';
        }
        return { category: 'phap_bao', subcategory: sub };
    }

    // 12. Nguyên Liệu
    const isMaterial = ['material', 'herb', 'ore', 'wood', 'seed', 'spirit_stone'].includes(type);
    if (isMaterial) {
        let sub = 'thien_tai';
        let subSub = 'default';

        const isHerb = type === 'herb' || type === 'seed';
        const isWood = type === 'wood';
        const isOre = type === 'ore' || type === 'spirit_stone';
        const isLiquid = id.includes('dich') || id.includes('tuy') || name.includes('Dịch') || name.includes('Tủy');
        const isYeuThu = id.includes('yeu_') || id.includes('yeu_dan') || id.includes('yeu_huyet') || id.includes('yeu_cot') || name.includes('Yêu');

        if (isHerb) {
            sub = 'linh_duoc';
            if (name.includes('Vạn Niên') || id.includes('van_nien')) {
                subSub = 'van_nien';
            } else if (name.includes('10000 năm') || name.includes('Vạn Năm') || id.includes('cao')) {
                subSub = '10000_nam';
            } else if (name.includes('1000 năm') || id.includes('1000y')) {
                subSub = '1000_nam';
            } else if (name.includes('100 năm') || id.includes('100y')) {
                subSub = '100_nam';
            } else {
                subSub = 'duoi_100_nam';
            }
        } else if (isWood) {
            sub = 'linh_moc';
            if (name.includes('Lôi') || id.includes('loi')) {
                subSub = 'loi';
            } else if (name.includes('Hỏa') || id.includes('hoa')) {
                subSub = 'hoa';
            } else if (name.includes('Âm') || id.includes('am')) {
                subSub = 'am';
            } else if (name.includes('Dưỡng Hồn') || id.includes('duong_hon')) {
                subSub = 'duong_hon';
            } else {
                subSub = 'loi';
            }
        } else if (isOre) {
            sub = 'linh_khoang';
            if (type === 'spirit_stone' || name.includes('Tinh Thạch') || id.includes('tinh_thach') || id.includes('spirit_stone') || id.startsWith('ling_thach_')) {
                subSub = 'tinh_thach';
            } else if (name.includes('Thiết') || name.includes('Kim') || id.includes('thiet') || id.includes('kim')) {
                subSub = 'kim_loai';
            } else if (name.includes('Ngọc') || id.includes('ngoc')) {
                subSub = 'ngoc_thach';
            } else {
                subSub = 'di_khoang';
            }
        } else if (isLiquid) {
            sub = 'linh_dich';
            if (name.includes('Luyện Thể') || id.includes('luyen_the')) {
                subSub = 'luyen_the';
            } else if (name.includes('Dưỡng Hồn') || id.includes('duong_hon')) {
                subSub = 'duong_hon';
            } else if (name.includes('Tu Luyện') || id.includes('tu_luyen')) {
                subSub = 'tu_luyen';
            } else {
                subSub = 'thien_dia';
            }
        } else if (isYeuThu) {
            sub = 'yeu_thu';
            if (id.includes('cot') || name.includes('Cốt')) {
                subSub = 'yeu_cot';
            } else if (id.includes('huyet') || name.includes('Huyết')) {
                subSub = 'yeu_huyet';
            } else if (id.includes('dan') || name.includes('Đan')) {
                subSub = 'yeu_dan';
            } else if (name.includes('Da') || name.includes('Lông')) {
                subSub = 'da_long';
            } else if (name.includes('Gân')) {
                subSub = 'gan';
            } else if (name.includes('Trảo') || name.includes('Móng')) {
                subSub = 'trao';
            } else if (name.includes('Nanh') || name.includes('Răng')) {
                subSub = 'yeu_nanh';
            } else {
                subSub = 'yeu_giac';
            }
        } else if (id.includes('luyen_the') || name.includes('Luyện Thể Tài Liệu')) {
            sub = 'luyen_the';
            if (id.includes('chan_linh')) {
                subSub = 'chan_linh_huyet';
            } else if (id.includes('huyet')) {
                subSub = 'yeu_huyet';
            } else if (id.includes('cot')) {
                subSub = 'linh_cot';
            } else {
                subSub = 'luyen_the_linh_qua';
            }
        } else if (id.includes('duong_hon') || name.includes('Dưỡng Hồn')) {
            sub = 'duong_hon';
            if (id.includes('moc')) {
                subSub = 'duong_hon_moc';
            } else if (id.includes('thach')) {
                subSub = 'hon_thach';
            } else if (id.includes('tinh')) {
                subSub = 'hon_tinh';
            } else if (id.includes('dan')) {
                subSub = 'duong_than_dan';
            } else {
                subSub = 'hon_thu_tai_lieu';
            }
        } else {
            sub = 'thien_tai';
            subSub = 'default';
        }

        return { category: 'nguyen_lieu', subcategory: sub, subSubcategory: subSub };
    }

    // 13. Kỳ Vật Dị Bảo (including fallback and former Tạp Vật)
    let sub = 'default';
    if (type === 'storage' || id.includes('tui_tru_vat') || id.includes('tru_vat') || id.includes('merchant') || id.includes('token_merchant')) {
        sub = 'default';
    } else if (type === 'map' || name.includes('Bản Đồ') || id.includes('ban_do')) {
        sub = 'ban_do';
    } else if (name.includes('Lệnh Bài') || name.includes('Lệnh') || id.includes('lenh_bai') || id.includes('lenh')) {
        sub = 'lenh_bai';
    } else if (name.includes('Chìa Khóa') || id.includes('chia_khoa') || id.includes('key')) {
        sub = 'chia_khoa';
    } else if (name.includes('Ngọc Giản') || id.includes('ngoc_gian')) {
        sub = 'ngoc_gian';
    }

    return { category: 'ky_vat_di_bao', subcategory: sub };
}

export function classifyItem(item) {
    const raw = _classifyItemRaw(item);
    if (!raw.allClassifications) {
        raw.allClassifications = [
            {
                category: raw.category,
                subcategory: raw.subcategory || 'default',
                subSubcategory: raw.subSubcategory || 'default'
            }
        ];
    }
    return raw;
}
